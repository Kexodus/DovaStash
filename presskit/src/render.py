# ---------------------------------------------------------------- data.js
def write_data_js():
    templates = []
    for f in sorted((DATA / "Templates").rglob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        folder = f.parent.name
        cell_file = d.get("cell", "").split("|")[0]
        if folder == "CreationClub":
            group = "Creation Club"
        elif cell_file.lower() == "hearthfires.esm":
            group = "Hearthfire"
        else:
            group = "Vanilla"
        templates.append({"name": d["name"], "group": group, "cellFile": cell_file,
                          "containers": len(d.get("containers", []))})
    cats = json.loads((DATA / "Categories" / "00_Default.json").read_text(
        encoding="utf-8"))["categories"]
    # Group-only entries (no "match": "weapons", "armor"...) name a group; they sort nothing themselves.
    categories = [{"id": c["id"], "name": c["name"]} for c in cats if c.get("match")]
    js = ("/* Generated by render.py from dist/Data/SKSE/Plugins/DovaStash. Do not edit. */\n"
          "window.DS_DATA = " + json.dumps({"templates": templates,
                                            "categories": categories}, indent=1) + ";\n")
    (SRC / "data.js").write_text(js, encoding="utf-8")
    return len(templates), len(categories)


# ---------------------------------------------------------------- render
def render(job):
    page, query, w, h, name, transparent = job
    url = (SRC / page).as_uri()
    # w/h pin the page box: Edge enforces a minimum window width, so small
    # canvases (256 px) must not depend on the viewport for centring.
    url += "?" + urllib.parse.urlencode({**query, "w": w, "h": h})
    out = OUT / name
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="ds_edge_", ignore_cleanup_errors=True) as prof:
        args = [EDGE, "--headless=new", "--disable-gpu", "--hide-scrollbars",
                "--force-device-scale-factor=1", f"--window-size={w},{h}",
                "--allow-file-access-from-files", "--virtual-time-budget=5000",
                "--disable-lcd-text",
                "--no-first-run", "--disable-extensions",
                f"--user-data-dir={prof}", f"--screenshot={out}"]
        if transparent:
            args.append("--default-background-color=00000000")
        args.append(url)
        if out.exists():
            out.unlink()
        subprocess.run(args, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                       timeout=120)
    return out


# ---------------------------------------------------------------- PNG checks
def png_chunks(data):
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("not a PNG")
    pos = 8
    while pos < len(data):
        (length,) = struct.unpack(">I", data[pos:pos + 4])
        ctype = data[pos + 4:pos + 8]
        yield ctype, data[pos + 8:pos + 8 + length]
        pos += 12 + length


def png_info(path):
    data = path.read_bytes()
    for ctype, body in png_chunks(data):
        if ctype == b"IHDR":
            w, h, depth, color = struct.unpack(">IIBB", body[:10])
            return w, h, depth, color
    raise ValueError("no IHDR")


def png_rows(path):
    """Decode an 8-bit RGB/RGBA PNG; yields (bytes-per-pixel, row bytearray)."""
    data = path.read_bytes()
    idat = b""
    for ctype, body in png_chunks(data):
        if ctype == b"IHDR":
            w, h, depth, color = struct.unpack(">IIBB", body[:10])
        elif ctype == b"IDAT":
            idat += body
    if depth != 8 or color not in (2, 6):
        raise ValueError(f"unsupported PNG format depth={depth} color={color}")
    bpp = 3 if color == 2 else 4
    raw = zlib.decompress(idat)
    stride = w * bpp
    prev = bytearray(stride)
    pos = 0
    for _ in range(h):
        ft = raw[pos]
        line = bytearray(raw[pos + 1:pos + 1 + stride])
        pos += 1 + stride
        if ft == 1:
            for i in range(bpp, stride):
                line[i] = (line[i] + line[i - bpp]) & 255
        elif ft == 2:
            for i in range(stride):
                line[i] = (line[i] + prev[i]) & 255
        elif ft == 3:
            for i in range(stride):
                left = line[i - bpp] if i >= bpp else 0
                line[i] = (line[i] + ((left + prev[i]) >> 1)) & 255
        elif ft == 4:
            for i in range(stride):
                a = line[i - bpp] if i >= bpp else 0
                b = prev[i]
                c = prev[i - bpp] if i >= bpp else 0
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pr = a if (pa <= pb and pa <= pc) else (b if pb <= pc else c)
                line[i] = (line[i] + pr) & 255
        yield bpp, line
        prev = line


def png_is_neutral(path):
    """True if every pixel has R == G == B (no colour anywhere)."""
    for bpp, line in png_rows(path):
        if line[0::bpp] != line[1::bpp] or line[1::bpp] != line[2::bpp]:
            return False
    return True


def png_alpha_ok(path):
    """Transparent variants: the corner must be fully clear and some pixel opaque."""
    first = True
    opaque = False
    for bpp, line in png_rows(path):
        if bpp != 4:
            return False
        if first and line[3] != 0:
            return False
        first = False
        opaque = opaque or (255 in line[3::4])
    return opaque


def main(argv):
    check_gray = "--check-gray" in argv
    filters = [a for a in argv if not a.startswith("--")]
    n_t, n_c = write_data_js()
    print(f"data.js: {n_t} templates, {n_c} categories")
    todo = [j for j in jobs() if not filters or any(f in j[4] for f in filters)]
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        list(pool.map(render, todo))
    failures = 0
    for page, query, w, h, name, transparent in todo:
        path = OUT / name
        if not path.exists():
            print(f"FAIL {name}: not rendered")
            failures += 1
            continue
        pw, ph, depth, color = png_info(path)
        size = path.stat().st_size
        problems = []
        if (pw, ph) != (w, h):
            problems.append(f"size {pw}x{ph} != {w}x{h}")
        if transparent and (color != 6 or not png_alpha_ok(path)):
            problems.append("background is not transparent")
        if size > MAX_BYTES:
            problems.append(f"{size} bytes > {MAX_BYTES}")
        if check_gray and not png_is_neutral(path):
            problems.append("contains non-neutral (colored) pixels")
        status = "FAIL" if problems else "ok  "
        failures += bool(problems)
        print(f"{status} {name:52s} {pw}x{ph} {size / 1024:7.1f} KB "
              + "; ".join(problems))
    print(f"{len(todo) - failures}/{len(todo)} ok")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
